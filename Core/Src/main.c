/**
 * @brief  The application entry point.
 * @retval int
 */
int main(void) {

	/* USER CODE BEGIN 1 */

	/* USER CODE END 1 */
	/* MCU Configuration--------------------------------------------------------*/

	/* Reset of all peripherals, Initializes the Flash interface and the Systick. */
	HAL_Init();

	/* USER CODE BEGIN Init */

	/* USER CODE END Init */

	/* Configure the system clock */
	SystemClock_Config();

	/* USER CODE BEGIN SysInit */

	/* USER CODE END SysInit */

	/* Initialize all configured peripherals */
	MX_GPIO_Init();
	MX_USART2_UART_Init();
	I2C_BusClear(&hi2c1);
	MX_I2C1_Init();

	HAL_Delay(100); // Give the MPU6050 time to power up and become ready before communicating with it.

	MPU6050_Data imu;
	Attitude attitude;
	uint32_t dt_f; // delay time since last mpu6090 values update and fusion
	uint32_t dt_t; // time interval for telemetry
	uint32_t current_time;
	uint8_t cont_errors = 0;

	HAL_StatusTypeDef status;

	status = MPU6050_Init(&hi2c1);
	while(status != HAL_OK) {
		I2C_BusClear(&hi2c1);
		MX_I2C1_Init();
		HAL_Delay(200);
		if(++cont_errors > 9) {
			printf("Init/recovery fail, %d", status);
			return 1;
		}
		status = MPU6050_Init(&hi2c1);
	}

	cont_errors = 0;
	status = MPU6050_CalibrateGyro();
	while(status != HAL_OK) {
		HAL_Delay(1000);
		if(++cont_errors > 9) {
			printf("Calibration fail, %d", status);
			return 1;
		}
		status = MPU6050_CalibrateGyro();
	}

	cont_errors = 0;
	status = MPU6050_Read(&imu);
	while(status != HAL_OK) {
		HAL_Delay(100);
		if(++cont_errors > 9) {
			printf("Read fail, %d", status);
		}
		status = MPU6050_Read(&imu);
	}
	cont_errors = 0;

	sensorFusion_Init(&imu, &attitude);

	uint32_t previous_fusion_time = 0;
	uint32_t previous_telemetry_time = 0;

	//main loop
	while (1) {
		cont_errors = 0;
		current_time = HAL_GetTick();
		dt_f = current_time - previous_fusion_time;
		dt_t = current_time - previous_telemetry_time;

		if(dt_f > FUSION_PERIOD) {
			status = MPU6050_Read(&imu);

			if(status != HAL_OK) {
			printf("MPU lost, recovering");
				while(status != HAL_OK) {
					I2C_BusClear(&hi2c1);
					MX_I2C1_Init();
					HAL_Delay(200);
					if(++cont_errors > 9) {
						printf("Can't recover I2C bus, exiting\r\n");
						return 1;
					}
					status = MPU6050_Read(&imu);
				}
			} else {
				cont_errors = 0;
			}

			sensorFusion_Update(&imu, dt_f, &attitude);
			previous_fusion_time += FUSION_PERIOD;
		}

		if(dt_t > TELEMETRY_PERIOD) {
			printf("Roll: %.2f\r\n"
				"Pitch: %.2f\r\n"
				"dt: %lu\r\n\r\n",
				attitude.roll, attitude.pitch, dt_t);
			previous_telemetry_time += TELEMETRY_PERIOD;
		}
	}
	/* USER CODE END 3 */
}

